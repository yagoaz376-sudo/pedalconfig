// Service worker: deixa o PedalConfig abrir sem internet depois da primeira vez.
// Rede primeiro (sempre pega a versao nova quando tem internet); sem rede, usa a copia guardada.
const CACHE = 'pedalconfig-20261124192243';
const FILES = ['./', 'index.html', 'style.css', 'model.js', 'midi.js', 'lcd.js', 'app.js', 'manifest.json', 'icon-192.png', 'icon-512.png'];
self.addEventListener('install', e => { e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES)).then(() => self.skipWaiting())); });
self.addEventListener('activate', e => {
  e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', e => {
  if (e.request.method !== 'GET' || new URL(e.request.url).origin !== location.origin) return;
  e.respondWith(fetch(e.request, { cache: 'no-cache' }).then(r => {   // no-cache: sempre confere com o servidor (o GitHub guarda 10 min)
    if (r.ok) { const copy = r.clone(); caches.open(CACHE).then(c => c.put(e.request, copy)); }
    return r;
  }).catch(() => caches.match(e.request, { ignoreSearch: true }).then(r => r || caches.match('./'))));
});
